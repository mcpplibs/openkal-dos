#!/bin/sh
# Assembles the stub and writes tools/src/stub_bytes.h, the bytes the seal writes before an
# executable. Run after changing stub/stub.S; the result is committed, so that the seal builds
# on a machine whose assembler has no 16-bit x86 (an aarch64 host's).
#   LLVM=<dir of clang and ld.lld> stub/build.sh
set -eu
here=$(cd "$(dirname "$0")" && pwd)
LLVM=${LLVM:-$(dirname "$(command -v clang)")}
work=$(mktemp -d)
trap 'rm -f "$work/stub.o" "$work/stub.bin"; rmdir "$work"' EXIT
"$LLVM/clang" --target=i386-unknown-none-elf -c "$here/stub.S" -o "$work/stub.o"
"$LLVM/ld.lld" -m elf_i386 --oformat binary --image-base=0 -Ttext=0 -e _okdos_stub "$work/stub.o" -o "$work/stub.bin"
python3 - "$work/stub.bin" "$here/../tools/src/stub_bytes.h" <<'PY'
import sys, hashlib
b = open(sys.argv[1], 'rb').read()
lines = ['// Generated by stub/build.sh from stub/stub.S; do not edit.',
         f'// {len(b)} bytes, sha256 {hashlib.sha256(b).hexdigest()}',
         '#pragma once', 'inline constexpr unsigned char kOkdosStub[] = {']
for i in range(0, len(b), 16):
    lines.append('    ' + ', '.join(f'0x{x:02x}' for x in b[i:i+16]) + ',')
lines.append('};')
open(sys.argv[2], 'w').write('\n'.join(lines) + '\n')
PY
echo "stub: $(wc -c < "$work/stub.bin") bytes"
